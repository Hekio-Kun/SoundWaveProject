CREATE TABLE content_reports
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    track_id             BIGINT               NOT NULL,
    submitted_by_user_id BIGINT               NOT NULL,
    handled_by_user_id   BIGINT               NULL,
    category             VARCHAR(50)          NOT NULL,
    description          VARCHAR(2000)       NOT NULL,
    status               VARCHAR(30)          NOT NULL
        CONSTRAINT DF_content_reports_status DEFAULT 'PENDING',
    resolution_note      VARCHAR(2000)       NULL,
    created_at           TIMESTAMP(3) WITHOUT TIME ZONE         NOT NULL
        CONSTRAINT DF_content_reports_created_at DEFAULT timezone('UTC', CURRENT_TIMESTAMP(3)),
    handled_at           TIMESTAMP(3) WITHOUT TIME ZONE         NULL,
    updated_at           TIMESTAMP(3) WITHOUT TIME ZONE         NOT NULL
        CONSTRAINT DF_content_reports_updated_at DEFAULT timezone('UTC', CURRENT_TIMESTAMP(3)),

    CONSTRAINT PK_content_reports PRIMARY KEY (id),
    CONSTRAINT FK_content_reports_tracks
        FOREIGN KEY (track_id) REFERENCES tracks(id),
    CONSTRAINT FK_content_reports_submitter_app_users
        FOREIGN KEY (submitted_by_user_id) REFERENCES app_users(id),
    CONSTRAINT FK_content_reports_handler_app_users
        FOREIGN KEY (handled_by_user_id) REFERENCES app_users(id),
    CONSTRAINT CK_content_reports_category
        CHECK (category IN
            ('COPYRIGHT', 'INAPPROPRIATE_CONTENT', 'INCORRECT_METADATA', 'OTHER')),
    CONSTRAINT CK_content_reports_status
        CHECK (status IN ('PENDING', 'RESOLVED', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT CK_content_reports_handling
        CHECK (
            (status IN ('PENDING', 'WITHDRAWN') AND handled_at IS NULL)
            OR
            (status IN ('RESOLVED', 'REJECTED')
                AND handled_by_user_id IS NOT NULL
                AND handled_at IS NOT NULL
                AND resolution_note IS NOT NULL)
        )
);
CREATE INDEX IX_content_reports_submitter
    ON content_reports(submitted_by_user_id, created_at DESC);
CREATE INDEX IX_content_reports_moderation_queue
    ON content_reports(status, created_at)
    INCLUDE (track_id, submitted_by_user_id, category);
