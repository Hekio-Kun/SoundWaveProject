CREATE TABLE tracks
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uploader_user_id        BIGINT               NOT NULL,
    album_id                BIGINT               NULL,
    genre_id                BIGINT               NOT NULL,
    title                   VARCHAR(200)        NOT NULL,
    slug                    VARCHAR(220)         NOT NULL,
    description             VARCHAR(2000)       NULL,
    track_number            SMALLINT             NULL,
    publication_status      VARCHAR(30)          NOT NULL
        CONSTRAINT DF_tracks_publication_status DEFAULT 'DRAFT',
    approved_at             TIMESTAMP(3) WITHOUT TIME ZONE         NULL,
    latest_rejection_reason VARCHAR(1000)       NULL,
    audio_public_id         VARCHAR(255)        NOT NULL,
    audio_url               VARCHAR(2048)       NOT NULL,
    audio_format            VARCHAR(20)          NOT NULL,
    duration_ms             INT                  NOT NULL,
    cover_public_id         VARCHAR(255)        NULL,
    cover_url               VARCHAR(2048)       NULL,
    play_count_cache        BIGINT               NOT NULL
        CONSTRAINT DF_tracks_play_count_cache DEFAULT 0,
    created_at              TIMESTAMP(3) WITHOUT TIME ZONE         NOT NULL
        CONSTRAINT DF_tracks_created_at DEFAULT timezone('UTC', CURRENT_TIMESTAMP(3)),
    updated_at              TIMESTAMP(3) WITHOUT TIME ZONE         NOT NULL
        CONSTRAINT DF_tracks_updated_at DEFAULT timezone('UTC', CURRENT_TIMESTAMP(3)),

    CONSTRAINT PK_tracks PRIMARY KEY (id),
    CONSTRAINT UQ_tracks_slug UNIQUE (slug),
    CONSTRAINT FK_tracks_uploader_app_users
        FOREIGN KEY (uploader_user_id) REFERENCES app_users(id),
    CONSTRAINT FK_tracks_albums
        FOREIGN KEY (album_id) REFERENCES albums(id) ON DELETE SET NULL,
    CONSTRAINT FK_tracks_genres
        FOREIGN KEY (genre_id) REFERENCES genres(id),
    CONSTRAINT CK_tracks_publication_status
        CHECK (publication_status IN
            ('DRAFT', 'PENDING', 'PUBLISHED', 'REJECTED', 'TAKEN_DOWN')),
    CONSTRAINT CK_tracks_track_number
        CHECK (track_number IS NULL OR track_number > 0),
    CONSTRAINT CK_tracks_duration_ms
        CHECK (duration_ms >= 0),
    CONSTRAINT CK_tracks_play_count_cache
        CHECK (play_count_cache >= 0)
);
CREATE INDEX IX_tracks_public_catalog
    ON tracks(publication_status, genre_id, created_at DESC)
    INCLUDE (title, slug, uploader_user_id, album_id, cover_url, duration_ms, play_count_cache);
CREATE INDEX IX_tracks_uploader_user_id
    ON tracks(uploader_user_id, publication_status, created_at DESC);
CREATE INDEX IX_tracks_album_id
    ON tracks(album_id, track_number);
CREATE TABLE track_submissions
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    track_id             BIGINT               NOT NULL,
    submitted_by_user_id BIGINT               NOT NULL,
    reviewer_user_id     BIGINT               NULL,
    status               VARCHAR(30)          NOT NULL
        CONSTRAINT DF_track_submissions_status DEFAULT 'PENDING',
    submitter_note       VARCHAR(2000)       NULL,
    reviewer_note        VARCHAR(2000)       NULL,
    rejection_reason     VARCHAR(1000)       NULL,
    submitted_at         TIMESTAMP(3) WITHOUT TIME ZONE         NOT NULL
        CONSTRAINT DF_track_submissions_submitted_at DEFAULT timezone('UTC', CURRENT_TIMESTAMP(3)),
    reviewed_at          TIMESTAMP(3) WITHOUT TIME ZONE         NULL,

    CONSTRAINT PK_track_submissions PRIMARY KEY (id),
    CONSTRAINT FK_track_submissions_tracks
        FOREIGN KEY (track_id) REFERENCES tracks(id),
    CONSTRAINT FK_track_submissions_submitter_app_users
        FOREIGN KEY (submitted_by_user_id) REFERENCES app_users(id),
    CONSTRAINT FK_track_submissions_reviewer_app_users
        FOREIGN KEY (reviewer_user_id) REFERENCES app_users(id),
    CONSTRAINT CK_track_submissions_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT CK_track_submissions_review_result
        CHECK (
            (status = 'PENDING' AND reviewed_at IS NULL)
            OR
            (status IN ('APPROVED', 'REJECTED')
                AND reviewer_user_id IS NOT NULL
                AND reviewed_at IS NOT NULL)
        ),
    CONSTRAINT CK_track_submissions_rejection_reason
        CHECK (status <> 'REJECTED' OR rejection_reason IS NOT NULL)
);
CREATE UNIQUE INDEX UX_track_submissions_one_pending_per_track
    ON track_submissions(track_id)
    WHERE status = 'PENDING';
CREATE INDEX IX_track_submissions_moderation_queue
    ON track_submissions(status, submitted_at)
    INCLUDE (track_id, submitted_by_user_id, reviewer_user_id);
