CREATE TABLE roles
(
    id          SMALLINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code        VARCHAR(30)             NOT NULL,
    name        VARCHAR(80)            NOT NULL,
    description VARCHAR(500)           NULL,
    created_at  TIMESTAMP(3) WITHOUT TIME ZONE            NOT NULL
        CONSTRAINT DF_roles_created_at DEFAULT timezone('UTC', CURRENT_TIMESTAMP(3)),

    CONSTRAINT PK_roles PRIMARY KEY (id),
    CONSTRAINT UQ_roles_code UNIQUE (code)
);
CREATE TABLE app_users
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    role_id           SMALLINT              NOT NULL,
    email             VARCHAR(320)         NOT NULL,
    password_hash     VARCHAR(255)          NOT NULL,
    status            VARCHAR(30)           NOT NULL
        CONSTRAINT DF_app_users_status DEFAULT 'PENDING',
    email_verified_at TIMESTAMP(3) WITHOUT TIME ZONE          NULL,
    last_login_at     TIMESTAMP(3) WITHOUT TIME ZONE          NULL,
    deleted_at        TIMESTAMP(3) WITHOUT TIME ZONE          NULL,
    created_at        TIMESTAMP(3) WITHOUT TIME ZONE          NOT NULL
        CONSTRAINT DF_app_users_created_at DEFAULT timezone('UTC', CURRENT_TIMESTAMP(3)),
    updated_at        TIMESTAMP(3) WITHOUT TIME ZONE          NOT NULL
        CONSTRAINT DF_app_users_updated_at DEFAULT timezone('UTC', CURRENT_TIMESTAMP(3)),

    CONSTRAINT PK_app_users PRIMARY KEY (id),
    CONSTRAINT UQ_app_users_email UNIQUE (email),
    CONSTRAINT FK_app_users_roles
        FOREIGN KEY (role_id) REFERENCES roles(id),
    CONSTRAINT CK_app_users_status
        CHECK (status IN ('PENDING', 'ACTIVE', 'BANNED'))
);
CREATE INDEX IX_app_users_role_id
    ON app_users(role_id);
CREATE INDEX IX_app_users_status
    ON app_users(status)
    WHERE deleted_at IS NULL;
