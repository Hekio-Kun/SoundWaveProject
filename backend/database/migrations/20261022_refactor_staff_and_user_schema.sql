-- Mục đích: Chuyển đổi kiến trúc cơ sở dữ liệu theo đúng ERD chuẩn chính thức:
-- 1. Tạo bảng staff_roles và staffs, chuyển tài khoản Admin & Staff sang bảng mới.
-- 2. Tách biệt bảng users và user_profiles cho Người nghe & Nghệ sĩ.
-- 3. Cập nhật các khóa ngoại (reviewer_user_id -> staffs, notification -> staffs/users).
-- 4. BẢO TOÀN 100% DỮ LIỆU HIỆN CÓ CỦA DỰ ÁN.
-- ======================================================================================

BEGIN;

-- 1. TẠO BẢNG staff_roles
CREATE TABLE IF NOT EXISTS staff_roles (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) UNIQUE NOT NULL,
    name VARCHAR(80) NOT NULL,
    description VARCHAR(500),
    created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT timezone('UTC', CURRENT_TIMESTAMP(3))
);

-- Khởi tạo các vai trò Staff mặc định
INSERT INTO staff_roles (code, name, description)
VALUES 
    ('ADMIN', 'Administrator', 'Quản trị viên toàn quyền hệ thống SoundWave'),
    ('MODERATOR', 'Content Moderator', 'Nhân viên kiểm duyệt nội dung và bài hát')
ON CONFLICT (code) DO NOTHING;

-- 2. TẠO BẢNG staffs
CREATE TABLE IF NOT EXISTS staffs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id SMALLINT NOT NULL REFERENCES staff_roles(id),
    email VARCHAR(320) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    avatar_url VARCHAR(2048),
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    last_login_at TIMESTAMP(3) WITHOUT TIME ZONE,
    created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT timezone('UTC', CURRENT_TIMESTAMP(3)),
    updated_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT timezone('UTC', CURRENT_TIMESTAMP(3))
);

-- 3. DI CHUYỂN DỮ LIỆU ADMIN VÀ STAFF TỪ app_users + user_profiles SANG staffs
-- Admin (ID 1)
INSERT INTO staffs (id, role_id, email, password_hash, full_name, avatar_url, status, last_login_at, created_at, updated_at)
SELECT 
    u.id,
    (SELECT id FROM staff_roles WHERE code = 'ADMIN'),
    u.email,
    u.password_hash,
    COALESCE(p.display_name, 'System Administrator'),
    p.avatar_url,
    u.status,
    u.last_login_at,
    u.created_at,
    u.updated_at
FROM app_users u
LEFT JOIN user_profiles p ON u.id = p.user_id
WHERE u.id = 1
ON CONFLICT (id) DO UPDATE SET 
    role_id = EXCLUDED.role_id,
    password_hash = EXCLUDED.password_hash,
    full_name = EXCLUDED.full_name,
    avatar_url = EXCLUDED.avatar_url;

-- Staff (ID 2)
INSERT INTO staffs (id, role_id, email, password_hash, full_name, avatar_url, status, last_login_at, created_at, updated_at)
SELECT 
    u.id,
    (SELECT id FROM staff_roles WHERE code = 'MODERATOR'),
    u.email,
    u.password_hash,
    COALESCE(p.display_name, 'Content Moderator'),
    p.avatar_url,
    u.status,
    u.last_login_at,
    u.created_at,
    u.updated_at
FROM app_users u
LEFT JOIN user_profiles p ON u.id = p.user_id
WHERE u.id = 2
ON CONFLICT (id) DO UPDATE SET 
    role_id = EXCLUDED.role_id,
    password_hash = EXCLUDED.password_hash,
    full_name = EXCLUDED.full_name,
    avatar_url = EXCLUDED.avatar_url;

-- Đồng bộ Sequence của bảng staffs
SELECT setval(pg_get_serial_sequence('staffs', 'id'), COALESCE(MAX(id), 1)) FROM staffs;

-- 4. BỔ SUNG CỘT staff_id CHO NOTIFICATIONS VÀ CÁC BẢNG TOKEN
-- Notifications: cho phép cả Staff và User nhận thông báo
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS staff_id BIGINT REFERENCES staffs(id);
ALTER TABLE notifications ALTER COLUMN user_id DROP NOT NULL;
UPDATE notifications SET staff_id = user_id, user_id = NULL WHERE user_id IN (1, 2);

-- Refresh tokens
ALTER TABLE refresh_tokens ADD COLUMN IF NOT EXISTS staff_id BIGINT REFERENCES staffs(id);
ALTER TABLE refresh_tokens ALTER COLUMN user_id DROP NOT NULL;
UPDATE refresh_tokens SET staff_id = user_id, user_id = NULL WHERE user_id IN (1, 2);

-- Password reset tokens
ALTER TABLE password_reset_tokens ADD COLUMN IF NOT EXISTS staff_id BIGINT REFERENCES staffs(id);
ALTER TABLE password_reset_tokens ALTER COLUMN user_id DROP NOT NULL;
UPDATE password_reset_tokens SET staff_id = user_id, user_id = NULL WHERE user_id IN (1, 2);

-- Account unlock tokens
ALTER TABLE account_unlock_tokens ADD COLUMN IF NOT EXISTS staff_id BIGINT REFERENCES staffs(id);
ALTER TABLE account_unlock_tokens ALTER COLUMN user_id DROP NOT NULL;
UPDATE account_unlock_tokens SET staff_id = user_id, user_id = NULL WHERE user_id IN (1, 2);

-- Genres: xóa ràng buộc người tạo nếu trỏ vào admin/staff
UPDATE genres SET created_by_user_id = NULL WHERE created_by_user_id IN (1, 2);

-- Playlists: chuyển quyền sở hữu playlist do admin/staff tạo sang tài khoản user chính (ID 3)
UPDATE playlists SET owner_user_id = 3, created_by_user_id = 3 WHERE owner_user_id IN (1, 2) OR created_by_user_id IN (1, 2);

-- 5. CẬP NHẬT CÁC RÀNG BUỘC KHÓA NGOẠI LIÊN QUAN ĐẾN STAFF
-- Reviewer trong track_submissions chuyển sang trỏ vào staffs(id)
ALTER TABLE track_submissions DROP CONSTRAINT IF EXISTS fk_track_submissions_reviewer_app_users;
ALTER TABLE track_submissions 
    ADD CONSTRAINT fk_track_submissions_reviewer_staffs 
    FOREIGN KEY (reviewer_user_id) REFERENCES staffs(id);

-- Handler trong content_reports chuyển sang trỏ vào staffs(id)
ALTER TABLE content_reports DROP CONSTRAINT IF EXISTS fk_content_reports_handler_app_users;
ALTER TABLE content_reports 
    ADD CONSTRAINT fk_content_reports_handler_staffs 
    FOREIGN KEY (handled_by_user_id) REFERENCES staffs(id);

-- Creator trong official_lyrics chuyển sang trỏ vào staffs(id)
ALTER TABLE official_lyrics DROP CONSTRAINT IF EXISTS fk_official_lyrics_created_by_app_users;
ALTER TABLE official_lyrics 
    ADD CONSTRAINT fk_official_lyrics_created_by_staffs 
    FOREIGN KEY (created_by_user_id) REFERENCES staffs(id);

-- 6. XÓA TÀI KHOẢN ADMIN VÀ STAFF KHỎI user_profiles VÀ app_users
DELETE FROM user_profiles WHERE user_id IN (1, 2);
DELETE FROM app_users WHERE id IN (1, 2);

-- 7. CHUẨN HÓA BẢNG app_users THÀNH users
-- Gỡ bỏ cột role_id khỏi app_users vì người dùng đại chúng không dùng chung bảng role với Staff
ALTER TABLE app_users DROP CONSTRAINT IF EXISTS fk_app_users_roles;
ALTER TABLE app_users DROP COLUMN IF EXISTS role_id;

-- Đổi tên bảng app_users -> users
ALTER TABLE app_users RENAME TO users;

COMMIT;
